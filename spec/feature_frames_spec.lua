local AddonLoader = require("addon_loader")
local FakeGame = require("fake_game")

describe("Feature frames", function()
  local ns, game, db

  before_each(function()
    ns = AddonLoader.load()
    game = FakeGame.new(ns)
    game.knownTotems = { [1] = { { name = "Searing Totem", icon = 101 } }, [2] = {}, [3] = {}, [4] = {} }
    db = {}
  end)

  local function start()
    ns.Addon.Start(game, db)
    return game.icons.ImbueReminder, game.totemBars.TotemBar
  end

  describe("on first load", function()
    it("shows both Features, locked, at full size, in separate default places", function()
      local icon, bar = start()
      for _, frame in ipairs({ icon, bar }) do
        assert.is_true(frame.enabled)
        assert.is_false(frame.unlocked)
        assert.are.equal(1, frame.layout.scale)
      end
      assert.are_not.same(icon.layout, bar.layout)
      assert.is_false(bar.vertical)
    end)

    it("adds show, lock and size settings for each Feature", function()
      start()
      for _, id in ipairs({ "imbueReminderShown", "imbueReminderLocked", "imbueReminderSize",
        "totemBarShown", "totemBarLocked", "totemBarSize", "totemBarVertical" }) do
        assert.truthy(game:FindSetting(id))
      end
    end)
  end)

  describe("moving", function()
    it("can't happen while locked", function()
      local icon = start()
      assert.has_error(function() icon:DragTo("TOP", "TOP", 10, -20) end)
    end)

    it("moves each Feature on its own and remembers the place", function()
      local icon, bar = start()
      game:ChangeSetting("imbueReminderLocked", false)
      icon:DragTo("TOPLEFT", "TOPLEFT", 100, -80)
      assert.is_false(bar.unlocked)
      assert.are.same({ point = "TOPLEFT", relativePoint = "TOPLEFT", x = 100, y = -80, scale = 1 },
        icon.layout)

      local reloaded = FakeGame.new(ns)
      ns.Addon.Start(reloaded, db)
      assert.are.same(icon.layout, reloaded.icons.ImbueReminder.layout)
    end)
  end)

  describe("resizing", function()
    it("scales each Feature on its own, and remembers it", function()
      local icon, bar = start()
      game:ChangeSetting("totemBarSize", 150)
      assert.are.equal(1.5, bar.layout.scale)
      assert.are.equal(1, icon.layout.scale)
      local reloaded = FakeGame.new(ns)
      ns.Addon.Start(reloaded, db)
      assert.are.equal(1.5, reloaded.totemBars.TotemBar.layout.scale)
    end)

    it("offers sizes from 50% to 200%, defaulting to 100%", function()
      start()
      local size = game:FindSetting("imbueReminderSize")
      assert.are.equal(50, size.min)
      assert.are.equal(200, size.max)
      assert.are.equal(100, size.default)
    end)
  end)

  describe("locking", function()
    it("is a setting per Feature", function()
      local icon, bar = start()
      game:ChangeSetting("totemBarLocked", false)
      assert.is_true(bar.unlocked)
      assert.is_false(icon.unlocked)
      assert.is_false(game:FindSetting("totemBarLocked").get())
    end)

    it("is switched for every Feature with /st unlock and /st lock", function()
      local icon, bar = start()
      game:Type("/st unlock")
      assert.is_true(icon.unlocked)
      assert.is_true(bar.unlocked)
      game:Type("/st lock")
      assert.is_false(icon.unlocked)
      assert.is_false(bar.unlocked)
      assert.is_true(db.frames.imbueReminder.locked)
    end)

    it("is listed in /st usage", function()
      start()
      game:Type("/st")
      local usage = table.concat(game.printed, "\n")
      assert.truthy(usage:find("/st lock", 1, true))
      assert.truthy(usage:find("/st unlock", 1, true))
    end)
  end)

  describe("switching a Feature off", function()
    it("hides it", function()
      local icon, bar = start()
      game:ChangeSetting("imbueReminderShown", false)
      assert.is_false(icon.enabled)
      assert.is_true(bar.enabled)
    end)

    it("remembers it", function()
      start()
      game:ChangeSetting("totemBarShown", false)
      local reloaded = FakeGame.new(ns)
      ns.Addon.Start(reloaded, db)
      assert.is_false(reloaded.totemBars.TotemBar.enabled)
    end)

    it("leaves the Totem Macros alone while the Totem Bar is off", function()
      start()
      game:ChangeSetting("totemBarShown", false)
      game:DeleteMacroByPlayer("ST Fire")
      assert.is_nil(game.macros["ST Fire"])
      game:ChangeSetting("totemBarShown", true)
      assert.are.equal("#showtooltip", game.macros["ST Fire"])
    end)

    it("doesn't create Totem Macros when the Totem Bar starts switched off", function()
      db = { frames = { totemBar = { enabled = false } } }
      start()
      assert.are.same({}, game:MacroNamesStartingWith("ST "))
    end)
  end)

  describe("Totem Bar orientation", function()
    it("can be vertical, and is remembered", function()
      local _, bar = start()
      game:ChangeSetting("totemBarVertical", true)
      assert.is_true(bar.vertical)
      local reloaded = FakeGame.new(ns)
      ns.Addon.Start(reloaded, db)
      assert.is_true(reloaded.totemBars.TotemBar.vertical)
    end)
  end)

  describe("in combat", function()
    it("changes to the Totem Bar's frame wait until combat ends", function()
      local _, bar = start()
      game:Fire("combatStarted")
      game:ChangeSetting("totemBarSize", 120)
      game:ChangeSetting("totemBarVertical", true)
      game:ChangeSetting("totemBarShown", false)
      assert.are.equal(1, bar.layout.scale)
      assert.is_false(bar.vertical)
      assert.is_true(bar.enabled)
      game:Fire("combatEnded")
      assert.are.equal(1.2, bar.layout.scale)
      assert.is_true(bar.vertical)
      assert.is_false(bar.enabled)
    end)

    it("changes to the Imbue Reminder apply at once", function()
      local icon = start()
      game:Fire("combatStarted")
      game:ChangeSetting("imbueReminderSize", 80)
      assert.are.equal(0.8, icon.layout.scale)
    end)
  end)
end)
